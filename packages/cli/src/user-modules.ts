// Custom native modules (`nativeModules` in prosperokit.config.ts): generates the app's
// `.prosperokit/user-modules` crate and an overlay Cargo workspace (`.prosperokit/rust`) that is the
// framework's Rust workspace with `crates/pk-user-modules` replaced by that crate.
//
// Module crates reference the framework through `../../.prosperokit/rust/crates/pk-js`, so the
// overlay's `crates/*` entries are symlinks to the real crates (one package identity per crate).
import { existsSync } from 'node:fs'
import { copyFile, mkdir, readdir, readFile, rm, symlink, writeFile } from 'node:fs/promises'
import { isAbsolute, join, resolve } from 'node:path'
import type { ProsperoConfig } from './config.js'
import { hashBytes } from './hash.js'
import { appPaths, findRustWorkspace } from './paths.js'

export interface UserModule {
  /** Cargo package name. */
  crateName: string
  /** Absolute directory of the module crate. */
  dir: string
}

export function userModulesDir(appDir: string): string {
  return join(appPaths(appDir).prosperokitDir, 'user-modules')
}

export function overlayRoot(appDir: string): string {
  return join(appPaths(appDir).prosperokitDir, 'rust')
}

/** Cargo package name from a manifest's `[package]` table. */
export function parsePackageName(manifest: string): string | undefined {
  const section = /\[package\]([\s\S]*?)(?:\n\[|$)/.exec(manifest)?.[1]
  return section ? /^\s*name\s*=\s*"([^"]+)"/m.exec(section)?.[1] : undefined
}

export async function resolveUserModules(
  appDir: string,
  cfg: ProsperoConfig,
): Promise<UserModule[]> {
  const out: UserModule[] = []
  for (const p of cfg.nativeModules) {
    const dir = isAbsolute(p) ? p : resolve(appDir, p)
    const manifestFile = join(dir, 'Cargo.toml')
    if (!existsSync(manifestFile))
      throw new Error(`nativeModules: ${p} has no Cargo.toml (expected a Rust crate at ${dir})`)
    const crateName = parsePackageName(await readFile(manifestFile, 'utf8'))
    if (!crateName)
      throw new Error(`nativeModules: cannot read the package name from ${manifestFile}`)
    if (out.some((m) => m.crateName === crateName))
      throw new Error(`nativeModules: duplicate crate "${crateName}"`)
    out.push({ crateName, dir })
  }
  return out
}

export function generateManifest(modules: UserModule[], frameworkPath: string): string {
  const deps = modules.map((m) => `${m.crateName} = { path = ${JSON.stringify(m.dir)} }`)
  return `# Generated by prosperokit; do not edit.
[package]
name = "pk-user-modules"
version = "0.1.0"
edition = "2024"
license = "GPL-3.0-or-later"
publish = false

[dependencies]
pk-js = { path = ${JSON.stringify(frameworkPath)} }
${deps.join('\n')}
`
}

export function generateLib(modules: UserModule[]): string {
  const calls = modules.map((m) => `    ${m.crateName.replace(/-/g, '_')}::register(reg);`)
  return `// Generated by prosperokit; do not edit.
/// Registers every custom native module listed in \`nativeModules\`.
pub fn register_all(${modules.length ? 'reg' : '_reg'}: &mut pk_js::ModuleRegistry) {
${calls.join('\n')}
}
`
}

async function writeIfChanged(file: string, content: string): Promise<void> {
  if (existsSync(file) && (await readFile(file, 'utf8')) === content) return
  await writeFile(file, content)
}

/** Fingerprint of the module crates' sources (for tool caches). */
export async function modulesHash(modules: UserModule[]): Promise<string> {
  const parts: string[] = []
  async function walk(base: string, rel: string): Promise<void> {
    for (const e of await readdir(join(base, rel), { withFileTypes: true })) {
      if (e.name === 'target' || e.name === '.git') continue
      const r = rel ? `${rel}/${e.name}` : e.name
      if (e.isDirectory()) await walk(base, r)
      else if (e.isFile()) parts.push(`${base}/${r}:${hashBytes(await readFile(join(base, r)), 8)}`)
    }
  }
  for (const m of modules) await walk(m.dir, '')
  return hashBytes(parts.sort().join('\n'))
}

export interface PreparedWorkspace {
  /** Workspace to build in: the overlay when custom modules exist, else the framework workspace. */
  rustRoot: string
  /** The framework workspace; the overlay's entries are symlinks into it. */
  frameworkRoot: string
  /** True when `rustRoot` is an overlay (build `pk-runtime`/`pk-host` with `--features user-modules`). */
  userModules: boolean
  modules: UserModule[]
}

/** Generates the user-modules crate and the overlay workspace when `nativeModules` is non-empty. */
export async function prepareWorkspace(
  appDir: string,
  cfg: ProsperoConfig,
): Promise<PreparedWorkspace> {
  const real = findRustWorkspace()
  const modules = await resolveUserModules(appDir, cfg)
  if (modules.length === 0) {
    return { rustRoot: real, frameworkRoot: real, userModules: false, modules }
  }

  const crateDir = userModulesDir(appDir)
  await mkdir(join(crateDir, 'src'), { recursive: true })
  await writeIfChanged(
    join(crateDir, 'Cargo.toml'),
    generateManifest(modules, join(overlayRoot(appDir), 'crates', 'pk-js')),
  )
  await writeIfChanged(join(crateDir, 'src', 'lib.rs'), generateLib(modules))

  const overlay = overlayRoot(appDir)
  await rm(overlay, { recursive: true, force: true })
  await mkdir(join(overlay, 'crates'), { recursive: true })
  for (const e of await readdir(join(real, 'crates'), { withFileTypes: true })) {
    if (!e.isDirectory() || e.name === 'pk-user-modules') continue
    await symlink(join(real, 'crates', e.name), join(overlay, 'crates', e.name), 'dir')
  }
  await symlink(crateDir, join(overlay, 'crates', 'pk-user-modules'), 'dir')
  for (const f of [
    'Cargo.toml',
    'Cargo.lock',
    'rust-toolchain.toml',
    'clippy.toml',
    'rustfmt.toml',
  ]) {
    if (existsSync(join(real, f))) await copyFile(join(real, f), join(overlay, f))
  }
  for (const d of ['targets', 'scripts', '.cargo', 'kit']) {
    if (existsSync(join(real, d))) await symlink(join(real, d), join(overlay, d), 'dir')
  }
  return { rustRoot: overlay, frameworkRoot: real, userModules: true, modules }
}
